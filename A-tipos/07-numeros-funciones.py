import math

print(round(1.5)) #round() devuelve el número entero más cercano al valor ingresado, ya sea arriba o abajo
print(abs(-11)) #abs() devuelve el valor absoluto del valor ingrsado
#Estas dos son de las pocas funciones nativas que tiene python para numeros, pero existe la libreria math para solucionar eso:

print(math.ceil(1.2)) #Debuelve el proximo valor entero mas cercano
print(math.floor(1.7)) #Debuelve el anterior valor entero mas cercano
print(math.isnan(23)) #Devuelve si es un NaN
print(math.pow(10, 3)) #Otra forma de sacar un valor elevado a x potencia
print(math.sqrt(9))

#y existen muchisimos mas metodos dentro de la libreria de math 